"""Build the single-file, standard-library-only SEED tool."""

from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo


def build() -> Path:
    folder = Path(__file__).resolve().parent
    future = "from __future__ import annotations\n"
    core = (folder / "seed_ecb_core.py").read_text(encoding="utf-8").replace(future, "")
    gui = (folder / "seed_ecb_tool.py").read_text(encoding="utf-8").replace(future, "")
    gui = gui.replace("from seed_ecb_core import decode_value, encode_value, parse_key, transform_stream\n", "")
    output = folder / "SEED_ECB_portable.py"
    output.write_text(
        '"""SEED-ECB portable tool. Python 3.10+; no pip packages required.\n'
        'Generated by build_seed_portable.py from the core and GUI sources.\n"""\n\n'
        + future + "\n" + core + "\n\n" + gui,
        encoding="utf-8",
    )
    download_folder = folder / "downloads"
    download_folder.mkdir(exist_ok=True)
    with ZipFile(download_folder / "SEED_ECB_Python_portable.zip", "w", compression=ZIP_DEFLATED) as archive:
        for file in (output, folder / "시작_SEED_ECB.bat", folder / "SEED_ECB_사용안내.txt"):
            entry = ZipInfo(file.name, date_time=(1980, 1, 1, 0, 0, 0))
            entry.compress_type = ZIP_DEFLATED
            archive.writestr(entry, file.read_bytes())
    return output


if __name__ == "__main__":
    print(build())
